/**
 * تصنيف نيّة الرسالة: هل المستخدم يطلب مخرجاً جاهزاً للنشر/الإرسال، أم يسأل سؤالاً
 * أو يتحدث حديثاً عادياً؟ في الحالة الثانية يجيب الموظف كإنسان ذكي فقط — بلا مخرج
 * ولا لوحة نشر ولا صورة ولا طلب ربط حساب.
 */

export type ChatIntent = "smalltalk" | "question" | "work";

/** أفعال طلب مخرج فعلي. */
const WORK =
  /منشور|بوست|بوستات|كابشن|كاربشن|كاروسيل|ريل|ريلز|قصة|ستوري|تغريدة|ثريد|مقال|خطة|تقويم|كالندر|حملة|سكربت|سيناريو|إعلان|اعلان|بريد|إيميل|ايميل|رسالة تسويقية|صفحة هبوط|تصميم|صورة|فيديو|هاشتاق|هاشتاجات|جدول|جدولة|انشر|أنشر|نشر|اكتب|اكتبلي|اعملي|اعمل لي|جهّز|جهز|صمم|ولّد|ولد لي|حلّل|حلل|تقرير|فحص|افحص|بحث كلمات|ترتيب|أفكار|افكار/u;

/**
 * طلب صورة صريح: «ولدلي صورة»، «اعمل تصميم»، «بوستر»، «شعار»… في هذه الحالة
 * تُولَّد صورة فعلية أياً كان الموظف، ولا يُكتفى بوصف الصورة نصاً.
 */
const IMAGE_REQUEST =
  /(صورة|صور|صورًا|صوره|تصميم|تصاميم|ديزاين|بوستر|بوستر|ملصق|بانر|بنر|انفوجراف|إنفوجراف|لوجو|شعار|كرييتف|كريتف|غلاف|كوفر|مشهد|رسمة|رسم|illustration|image|design|poster|banner|logo|thumbnail)/iu;

/** أفعال توليد/إنشاء تجعل طلب الصورة صريحاً لا مجرد ذكر لكلمة صورة. */
const MAKE =
  /(ولّد|ولد|ولدلي|ولّدلي|اعمل|إعمل|اعملي|سوّ|سو لي|سويلي|صمم|صمّم|ارسم|إرسم|اصنع|أنشئ|انشئ|جهّز|جهز|اكتبلي|عايز|عاوز|أريد|اريد|ابغى|أبغى|هات|اعطني|أعطني|create|generate|make|draw|design)/iu;

/** هل الرسالة طلب صورة صريح؟ */
export function wantsImageRequest(message: string): boolean {
  const text = (message ?? "").trim();
  if (!text) return false;
  if (!IMAGE_REQUEST.test(text)) return false;
  // ذكر كلمة «صورة» وحدها في سؤال ليس طلب توليد.
  return MAKE.test(text) || /^\s*(صورة|تصميم|بوستر|شعار|بانر)/u.test(text);
}

/** تحيات وحديث اجتماعي قصير. */
const SMALL =
  /^(\s*[\p{P}\p{S}]*\s*)?(هاي|هلا|أهلا|اهلا|أهلاً|السلام عليكم|سلام|صباح الخير|مساء الخير|ازيك|إزيك|كيفك|كيف حالك|عامل ايه|عامل إيه|شكرا|شكراً|تمام|تسلم|يعطيك العافية|ok|okay|hi|hello|thanks)(?![\p{L}])/iu;

/**
 * يصنّف الرسالة. القاعدة: أي طلب فيه فعل إنتاج = عمل. غير ذلك سؤال أو دردشة،
 * ويجيب الموظف عليه مباشرة بذكاء بلا فرض خدماته.
 */
export function chatIntent(message: string): ChatIntent {
  const text = message.trim();
  if (!text) return "smalltalk";
  if (WORK.test(text)) return "work";
  if (SMALL.test(text) && text.length < 60) return "smalltalk";
  if (
    /[؟?]\s*$/.test(text) ||
    /^(مين|من|ايه|إيه|ما هو|ما هي|كام|كم|ليه|لماذا|امتى|إمتى|متى|فين|أين|وين|هل|ازاي|إزاي|كيف)(?![\p{L}])/u.test(
      text,
    )
  )
    return "question";
  return text.length > 160 ? "work" : "question";
}

/** التعليمات التي تُحقن حسب النية. */
export function intentBlock(intent: ChatIntent): string {
  if (intent === "work") return "";
  return [
    "## وضع المحادثة الحرة (إلزامي في هذه الرسالة)",
    intent === "smalltalk"
      ? "المستخدم يحادثك حديثاً عادياً. رد بجملة أو جملتين دافئتين بشريتين فقط."
      : "المستخدم يسألك سؤالاً ولم يطلب منك إنتاج شيء. أجب على السؤال نفسه إجابة مباشرة دقيقة مفيدة، بأقصر شكل يكفيه، مستنداً إلى الحقائق اللحظية إن وُجدت.",
    "ممنوع في هذه الرسالة: كتابة منشور أو مخرج جاهز، أو عرض خدماتك وقدراتك، أو ذكر النشر والجدولة والاعتماد، أو طلب ربط أي حساب، أو إضافة «الخطوة التالية»، أو توليد صورة.",
    'اجعل "deliverable" و"deliverables" و"needs_connection" و"image_prompt" كلها null.',
    "لا تفرض على المستخدم شيئاً لم يطلبه. إن كان لديك اقتراح مفيد جداً فاذكره كسؤال قصير في سطر واحد فقط عند الحاجة.",
  ].join("\n");
}
